def set_language(language: str | None) -> None:
    """Pick the language for generated texts from Home Assistant's language."""
    global _LANGUAGE
    code = (language or "en").lower().split("-")[0]
    _LANGUAGE = code if code in TEXTS else "en"


def language() -> str:
    return _LANGUAGE


def t(key: str, **values) -> str:
    text = TEXTS[_LANGUAGE].get(key) or TEXTS["en"][key]
    return text.format(**values) if values else text


def day_name(index: int) -> str:
    return t("days").split(",")[index]


def format_date(day: date, year: bool = False) -> str:
    """'16 Oct' / '16 окт' (with year: '16 Oct 2026')."""
    month = t("months").split(",")[day.month - 1]
    return f"{day.day:02d} {month}" + (f" {day.year}" if year else "")
